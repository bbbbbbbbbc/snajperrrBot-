const generatedCatalog: IntegrationDefinition[] = [];
const seenIds = new Set<string>();

for (const [category, spec] of Object.entries(CATEGORY_SPECS)) {
  for (const [name, protocol, domain, popular] of spec.items) {
    const baseSlug = name
      .toLowerCase()
      .normalize('NFD')
      .replace(/[\u0300-\u036f]/g, '')
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-|-$/g, '');
    let id = baseSlug;
    let suffix = 2;
    while (seenIds.has(id)) {
      id = `${baseSlug}-${suffix++}`;
    }
    seenIds.add(id);

    generatedCatalog.push({
      id,
      name,
      category,
      protocol,
      description: spec.descTemplate(name),
      docsUrl: `https://${domain}`,
      defaultEvents: spec.defaultEvents,
      popular: Boolean(popular),
    });
  }
}

